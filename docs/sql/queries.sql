-- 6.1. Вывести заявки вместе с именами их авторов и названиями статусов
SELECT 
    r.number AS 'Номер заявки', 
    r.title AS 'Тема', 
    u.name AS 'Заявитель', 
    s.name AS 'Статус'
FROM Requests r
JOIN Users u ON r.author_id = u.id
JOIN Statuses s ON r.status_id = s.id;

-- 6.2. Вывести заявки вместе с названиями категорий и именами назначенных исполнителей
SELECT 
    r.number AS 'Номер заявки', 
    r.title AS 'Тема', 
    c.name AS 'Категория', 
    u.name AS 'Исполнитель'
FROM Requests r
JOIN Categories c ON r.category_id = c.id
LEFT JOIN Users u ON r.assignee_id = u.id;